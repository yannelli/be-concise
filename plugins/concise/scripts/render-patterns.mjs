#!/usr/bin/env node
import { readdirSync, readFileSync, writeFileSync, existsSync, mkdirSync, rmSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { loadPacks } from "../hooks/lib/packs.mjs";

const HERE = dirname(fileURLToPath(import.meta.url));
export const REFERENCE_DIR = join(HERE, "..", "skills", "concise-rules", "references");
export const MARKER = "<!-- generated by scripts/render-patterns.mjs, do not edit -->";
export const COMMAND = "run: node plugins/concise/scripts/render-patterns.mjs";
export const MAX_LINES = 300;
const PART_NAME = /^ai-speak-patterns(?:-(\d+))?\.md$/;
const LITERAL = /[A-Za-z0-9 '’,!:-]/;
const NO_CWD = "/nonexistent-concise-cwd";
const CREDIT = "Built from the packs in `hooks/lib/patterns`. Each section names its own source.";

export const partName = (i) => (i === 0 ? "ai-speak-patterns.md" : `ai-speak-patterns-${i + 1}.md`);

const cell = (s) => String(s).replace(/\s*\n\s*/g, " ").replace(/\|/g, "\\|");
const code = (s) => `\`${cell(s)}\``;
const unique = (items) => [...new Set(items)];

function groupEnd(src, start) {
  let depth = 0;
  for (let i = start; i < src.length; i += 1) {
    if (src[i] === "\\") i += 1;
    else if (src[i] === "(") depth += 1;
    else if (src[i] === ")" && (depth -= 1) === 0) return i;
  }
  return -1;
}

function splitTop(src) {
  const parts = [];
  let depth = 0;
  let cur = "";
  for (let i = 0; i < src.length; i += 1) {
    const c = src[i];
    if (c === "(") depth += 1;
    if (c === ")") depth -= 1;
    if (c === "|" && depth === 0) {
      parts.push(cur);
      cur = "";
    } else cur += c;
  }
  parts.push(cur);
  return parts;
}

function expandBranch(src) {
  let forms = [""];
  let i = 0;
  while (i < src.length) {
    if (src[i] === "(") {
      if (src.slice(i, i + 3) !== "(?:") return null;
      const end = groupEnd(src, i);
      if (end < 0) return null;
      const inner = expandSource(src.slice(i + 3, end));
      if (!inner) return null;
      i = end + 1;
      const opts = src[i] === "?" ? ["", ...inner] : inner;
      if (src[i] === "?") i += 1;
      forms = forms.flatMap((f) => opts.map((o) => f + o));
      continue;
    }
    if (!LITERAL.test(src[i])) return null;
    const c = src[i];
    const opts = src[i + 1] === "?" ? ["", c] : [c];
    forms = forms.flatMap((f) => opts.map((o) => f + o));
    i += opts.length > 1 ? 2 : 1;
  }
  return forms;
}

/** Literal forms of a pattern source, or null when it uses anything past `(?:a|b)?` alternations. */
export function expandSource(src) {
  const out = [];
  for (const branch of splitTop(src)) {
    const forms = expandBranch(branch);
    if (!forms) return null;
    out.push(...forms);
  }
  return unique(out.filter((f) => f !== ""));
}

export function flaggedCell(entry) {
  if (typeof entry.show === "string" && entry.show !== "") return cell(entry.show);
  const src = entry.phrase ?? entry.opening ?? entry.regex;
  const forms = expandSource(src);
  const shown = forms ? forms.map(code).join(", ") : code(src);
  return typeof entry.opening === "string" ? `${shown} (sentence-initial)` : shown;
}

const patternRow = (entry) => `| ${flaggedCell(entry)} | ${cell(entry.fix)} |`;

function detectorRow(pack) {
  const what = pack.description || pack.category.description || `the ${pack.id} detector`;
  const pairs = Object.entries(pack.options).map(([k, v]) => code(`${k} = ${JSON.stringify(v)}`));
  return `| ${cell(what)} | ${pairs.length ? pairs.join(", ") : "reported with the measured value"} |`;
}

function presetsOf(packs) {
  const names = unique(packs.flatMap((p) => p.presets || []));
  return names.includes("all") ? names : [...names, "all"];
}

export function sections(packs) {
  const order = [];
  const byId = new Map();
  for (const pack of packs) {
    if (!pack.builtin || pack.feature !== "aiWriting") continue;
    if (!byId.has(pack.categoryId)) {
      byId.set(pack.categoryId, []);
      order.push(pack.categoryId);
    }
    byId.get(pack.categoryId).push(pack);
  }
  return order.map((id) => ({ id, packs: byId.get(id) }));
}

function sourceOf(packs) {
  const sources = unique(packs.map((p) => p.source).filter(Boolean));
  if (!sources.length) return "";
  const text = sources.join("; ");
  return ` Source: ${/[.!?]$/.test(text) ? text : `${text}.`}`;
}

function sectionLines(section) {
  const { description } = section.packs[0].category;
  const presets = presetsOf(section.packs).map(code).join(", ");
  const out = [`## ${section.id}`, "", `Presets: ${presets}.${sourceOf(section.packs)}`, ""];
  if (description) out.push(cell(description), "");
  out.push("| Flagged | Fix |", "|---|---|");
  for (const pack of section.packs) {
    for (const entry of pack.patterns) if (entry.tier !== 2) out.push(patternRow(entry));
    if (pack.detect) out.push(detectorRow(pack));
  }
  const tier2 = section.packs.flatMap((p) => p.patterns.filter((e) => e.tier === 2));
  if (tier2.length) out.push("", "| Flagged (tier 2) | Fix |", "|---|---|", ...tier2.map(patternRow));
  for (const pack of section.packs) if (pack.notes) out.push("", cell(pack.notes));
  out.push("");
  return out;
}

function indexRows(list, fileOf) {
  return list.map((section) => {
    const label = section.packs[0].category.label;
    const ids = section.packs.map((p) => code(p.id)).join(", ");
    const presets = presetsOf(section.packs).map(code).join(", ");
    return `| ${code(section.id)} | ${cell(label)} | ${ids} | ${presets} | ${code(fileOf.get(section.id))} |`;
  });
}

function header(part, parts, index) {
  const title = parts > 1 ? `# AI speak patterns, part ${part + 1}` : "# AI speak patterns";
  const nav =
    part === 0
      ? "Phrase patterns are case-insensitive. The left column holds the flagged text, the right column the fix the hook prints."
      : "The category index is in `ai-speak-patterns.md`.";
  const out = [MARKER, title, "", CREDIT, "", nav, ""];
  if (part === 0) out.push("| Category | Label | Pack | Presets | File |", "|---|---|---|---|---|", ...index, "");
  return out;
}

const headerSize = (part, count) => (part === 0 ? 10 + count : 7);

function planParts(blocks, count) {
  const files = [[]];
  let lines = headerSize(0, count);
  for (const block of blocks) {
    const next = headerSize(files.length, count);
    if (files[files.length - 1].length && lines + block.length >= MAX_LINES) {
      files.push([]);
      lines = next;
    }
    files[files.length - 1].push(block);
    lines += block.length;
  }
  return files;
}

/** Every generated file as a Map of file name to content, split so each part stays under 300 lines. */
export function render(packs) {
  const list = sections(packs);
  const blocks = list.map(sectionLines);
  const plan = planParts(blocks, list.length);
  const fileOf = new Map();
  let at = 0;
  plan.forEach((part, i) => part.forEach(() => fileOf.set(list[at++].id, partName(i))));
  const index = indexRows(list, fileOf);
  const out = new Map();
  plan.forEach((part, i) => {
    const lines = [...header(i, plan.length, index), ...part.flat()];
    while (lines[lines.length - 1] === "") lines.pop();
    out.set(partName(i), `${lines.join("\n")}\n`);
  });
  return out;
}

const staleIn = (dir) =>
  existsSync(dir) ? readdirSync(dir).filter((name) => PART_NAME.test(name)) : [];

function diff(dir, files) {
  const stale = [];
  for (const [name, content] of files) {
    const path = join(dir, name);
    const have = existsSync(path) ? readFileSync(path, "utf8") : null;
    if (have !== content) stale.push(path);
  }
  for (const name of staleIn(dir)) if (!files.has(name)) stale.push(join(dir, name));
  return stale;
}

async function main(argv) {
  const check = argv.includes("--check");
  const outAt = argv.indexOf("--out");
  const dir = outAt >= 0 ? argv[outAt + 1] : REFERENCE_DIR;
  const { packs } = await loadPacks({ cwd: NO_CWD });
  const files = render(packs);
  if (check) {
    const stale = diff(dir, files);
    if (!stale.length) return 0;
    for (const path of stale) console.log(path);
    console.log(COMMAND);
    return 1;
  }
  mkdirSync(dir, { recursive: true });
  for (const [name, content] of files) writeFileSync(join(dir, name), content);
  for (const name of staleIn(dir)) if (!files.has(name)) rmSync(join(dir, name));
  console.log(`wrote ${files.size} file(s) to ${dir}`);
  return 0;
}

const entry = process.argv[1] ? pathToFileURL(process.argv[1]).href : "";
if (import.meta.url === entry) process.exit(await main(process.argv.slice(2)));
