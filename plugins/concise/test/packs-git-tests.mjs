import { mkdtempSync, writeFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { ok, bad, withConfig, run, CHECK_EDIT, CHECK_BASH, CHECK_REPLY } from "./lib.mjs";

const dirs = [];
let seq = 0;

/** One tmp project per case, with only the pack under test enabled. */
function project(categories) {
  const dir = mkdtempSync(join(tmpdir(), "concise-git-"));
  dirs.push(dir);
  withConfig(dir, { checks: { prBody: false }, features: { aiWriting: { enabled: true, categories } } });
  seq += 1;
  return { dir, sid: `git-${process.pid}-${seq}` };
}

const cleanup = () => dirs.splice(0).forEach((dir) => rmSync(dir, { recursive: true, force: true }));

const heredoc = (body) => `"$(cat <<'EOF'\n${body}\nEOF\n)"`;
const bashEvent = (c, command) => ({ tool_name: "Bash", tool_input: { command }, cwd: c.dir, session_id: c.sid });
const writeEvent = (c, name, content) => ({
  tool_name: "Write",
  tool_input: { file_path: join(c.dir, name), content },
  cwd: c.dir,
  session_id: c.sid,
});

function transcript(c, text) {
  const path = join(c.dir, "t.jsonl");
  const user = { type: "user", message: { role: "user", content: [{ type: "text", text: "go" }] } };
  const reply = { type: "assistant", message: { role: "assistant", content: [{ type: "text", text }] } };
  writeFileSync(path, `${JSON.stringify(user)}\n${JSON.stringify(reply)}\n`);
  return path;
}

const HOOKS = {
  commit: (c, text) => run(CHECK_BASH, bashEvent(c, `git commit -m ${heredoc(text)}`)),
  command: (c, text) => run(CHECK_BASH, bashEvent(c, text)),
  gh: (c, text) => run(CHECK_BASH, bashEvent(c, `gh pr create --title "x" --body ${heredoc(text)}`)),
  comments: (c, text) => run(CHECK_EDIT, writeEvent(c, "a.ts", `${text}\nconst x = 1;\n`)),
  files: (c, text) => run(CHECK_EDIT, writeEvent(c, "doc.md", `${text}\n`)),
  reply: (c, text) =>
    run(CHECK_REPLY, { hook_event_name: "Stop", session_id: c.sid, cwd: c.dir, transcript_path: transcript(c, text) }),
};

const reasonOf = (r) => r.hookSpecificOutput?.permissionDecisionReason || r.reason || r.systemMessage || "";
const label = (text) => JSON.stringify(text.replace(/\s+/g, " ").slice(0, 46));

function fires(pack, via, text) {
  const name = `${pack} flags ${label(text)} in ${via}`;
  const reason = reasonOf(HOOKS[via](project([pack]), text));
  if (reason.includes(`(${pack}:`)) return ok(name);
  bad(name, `no ${pack} finding in ${JSON.stringify(reason).slice(0, 220)}`);
}

function quiet(pack, via, text) {
  const name = `${pack} passes ${label(text)} in ${via}`;
  const reason = reasonOf(HOOKS[via](project([pack]), text));
  if (reason === "") return ok(name);
  bad(name, `expected no finding, got ${JSON.stringify(reason).slice(0, 220)}`);
}

function runCases(title, cases) {
  console.log(`\n${title}`);
  for (const [pack, via, text, hit] of cases) (hit ? fires : quiet)(pack, via, text);
}

